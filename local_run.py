"""Local smoke run + writes data/precomputed.json (fallback for the UI, and
what lets the JS side be developed without Pyodide).

    python local_run.py [shots]
"""
import json
import sys
from pathlib import Path

from qiskit.providers.basic_provider import BasicSimulator

from quantum import runner

shots = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
data = runner.run_all(BasicSimulator(), shots=shots)

print(f"circuits in the single job: {len(runner.CIRCUIT_ORDER)}")
print(f"Bob marginal (Alice none/Z/X): "
      + ", ".join(f"{data['nosignal'][c]['bob']['p1']:.3f}" for c in ("none", "Z", "X")))
print(f"rho_B = {data['nosignal']['rho_bob']}")
print(f"CHSH quantum: {data['chsh']['overall']:.4f} ± {data['chsh']['sigma']:.4f}   "
      f"classical best: {data['chsh']['classical_best']}   Tsirelson: {data['chsh']['tsirelson_bound']:.4f}")
print(f"W leader  exactly-one: {data['leader']['exactly_one']:.3f}  split-brain: {data['leader']['split_brain']:.3f}  "
      f"no-leader: {data['leader']['no_leader']:.3f}  per-node: {[round(p,3) for p in data['leader']['per_node_leader']]}")
print(f"GHZ consensus agreement: {data['consensus']['agreement']:.3f}")
if "mermin" in data:
    print(f"Mermin-GHZ game: {data['mermin']['overall']:.3f}")

out = Path(__file__).parent / "data" / "precomputed.json"
out.parent.mkdir(exist_ok=True)
out.write_text(json.dumps(data, indent=1))
# JS module twin: Qollab lets main.js import './data/precomputed.js' with no fetch.
js = out.with_suffix(".js")
js.write_text("// generated by local_run.py — do not edit\nexport default "
              + json.dumps(data) + ";\n")
print(f"wrote {out} and {js.name} ({out.stat().st_size/1024:.1f} KB)")
